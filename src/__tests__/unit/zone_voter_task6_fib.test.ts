// ЗАДАЧА 6: Фибоначчи — строго гл. 12 ЯС.
// Книга: «Наиболее распространенными уровнями таких коррекций являются
// 50%-ный, а также 38%-ный и 62%-ный»; коррекция измеряется от КОНКРЕТНОГО
// движения A→B (рис. 12.1–12.7), а не от безымянного min/max окна.
import { describe, it, expect, beforeEach } from 'vitest';
import { Candle } from '../../utils/candle';
import { ZoneVoter } from '../../utils/zone_voter';

const mk = (time: number, open: number, high: number, low: number, close: number, volume = 100) =>
  new Candle({ time, open, high, low, close, volume });

describe('Задача 6: Fibonacci от направленного импульса (ЯС гл. 12)', () => {
  beforeEach(() => ZoneVoter.clearCache());

  // Направленный импульс high→low: экстремум high на баре 25, экстремум low на баре 75.
  const impulseHistory = [
    ...Array.from({ length: 20 }, (_, i) => mk(i + 1, 100, 100.3, 99.7, 100)),
    mk(21, 100, 100.2, 99.8, 100.1),
    mk(22, 100.1, 100.3, 99.9, 100.2),
    mk(23, 100.2, 100.4, 100.0, 100.3),
    mk(24, 100.3, 100.5, 100.1, 100.4),
    mk(25, 100.4, 100.6, 100.2, 100.5),                   // swing high = 100.6
    mk(26, 100.5, 100.6, 100.3, 100.4),
    mk(27, 100.4, 100.5, 100.2, 100.3),
    mk(28, 100.3, 100.4, 100.1, 100.2),
    mk(29, 100.2, 100.3, 100.0, 100.1),
    mk(30, 100.1, 100.2, 99.9, 100.0),
    mk(31, 100.0, 100.1, 99.8, 99.9),
    mk(32, 99.9, 100.0, 99.7, 99.8),
    mk(33, 99.8, 99.9, 99.6, 99.7),
    mk(34, 99.7, 99.8, 99.5, 99.6),
    mk(35, 99.6, 99.7, 99.4, 99.5),
    mk(36, 99.5, 99.6, 99.3, 99.4),
    mk(37, 99.4, 99.5, 99.2, 99.3),
    mk(38, 99.3, 99.4, 99.1, 99.2),
    mk(39, 99.2, 99.3, 99.0, 99.1),
    mk(40, 99.1, 99.2, 98.9, 99.0),
    mk(41, 99.0, 99.1, 98.8, 98.9),
    mk(42, 98.9, 99.0, 98.7, 98.8),
    mk(43, 98.8, 98.9, 98.6, 98.7),
    mk(44, 98.7, 98.8, 98.5, 98.6),
    mk(45, 98.6, 98.7, 98.4, 98.5),
    mk(46, 98.5, 98.6, 98.3, 98.4),
    mk(47, 98.4, 98.5, 98.2, 98.3),
    mk(48, 98.3, 98.4, 98.1, 98.2),
    mk(49, 98.2, 98.3, 98.0, 98.1),
    mk(50, 98.1, 98.2, 97.9, 98.0),
    mk(51, 98.0, 98.1, 97.8, 97.9),
    mk(52, 97.9, 98.0, 97.7, 97.8),
    mk(53, 97.8, 97.9, 97.6, 97.7),
    mk(54, 97.7, 97.8, 97.5, 97.6),
    mk(55, 97.6, 97.7, 97.4, 97.5),
    mk(56, 97.5, 97.6, 97.3, 97.4),
    mk(57, 97.4, 97.5, 97.2, 97.3),
    mk(58, 97.3, 97.4, 97.1, 97.2),
    mk(59, 97.2, 97.3, 97.0, 97.1),
    mk(60, 97.1, 97.2, 96.9, 97.0),
    mk(61, 97.0, 97.1, 96.8, 96.9),
    mk(62, 96.9, 97.0, 96.7, 96.8),
    mk(63, 96.8, 96.9, 96.6, 96.7),
    mk(64, 96.7, 96.8, 96.5, 96.6),
    mk(65, 96.6, 96.7, 96.4, 96.5),
    mk(66, 96.5, 96.6, 96.3, 96.4),
    mk(67, 96.4, 96.5, 96.2, 96.3),
    mk(68, 96.3, 96.4, 96.1, 96.2),
    mk(69, 96.2, 96.3, 96.0, 96.1),
    mk(70, 96.1, 96.2, 95.9, 96.0),
    mk(71, 96.0, 96.1, 95.8, 95.9),
    mk(72, 95.9, 96.0, 95.7, 95.8),
    mk(73, 95.8, 95.9, 95.6, 95.7),
    mk(74, 95.7, 95.8, 95.5, 95.6),
    mk(75, 95.6, 95.7, 95.4, 95.5),                       // swing low = 95.4
    mk(76, 95.5, 95.6, 95.3, 95.4),
    mk(77, 95.4, 95.5, 95.2, 95.3),
    mk(78, 95.3, 95.4, 95.1, 95.2),
    mk(79, 95.2, 95.3, 95.0, 95.1),
    mk(80, 95.1, 95.2, 94.9, 95.0),
  ];

  it('только книжные уровни 38/50/62%, без 23.6/78.6', () => {
    const supMap = new Map(); const resMap = new Map();
    (ZoneVoter as any).addFibonacciLevels(impulseHistory, supMap, resMap, {
      tolerance: 0.005, breakPct: 0.003, lookback: 150, swingSpan: 3,
    });
    const reasons = [...supMap.values(), ...resMap.values()].flatMap((d: any) => d.reasons);
    expect(reasons.some((r: string) => /23\.6/.test(r))).toBe(false);
    expect(reasons.some((r: string) => /78\.6/.test(r))).toBe(false);
    expect(reasons.some((r: string) => /38%/.test(r))).toBe(true);
    expect(reasons.some((r: string) => /50%/.test(r))).toBe(true);
    expect(reasons.some((r: string) => /62%/.test(r))).toBe(true);
  });

  it('нет псевдоцитаты «Нисон: "Уровни коррекции 38%, 50% и 62% часто выступают как зоны..."»', () => {
    const supMap = new Map(); const resMap = new Map();
    (ZoneVoter as any).addFibonacciLevels(impulseHistory, supMap, resMap, {
      tolerance: 0.005, breakPct: 0.003, lookback: 150, swingSpan: 3,
    });
    const reasons = [...supMap.values(), ...resMap.values()].flatMap((d: any) => d.reasons);
    expect(reasons.some((r: string) => /часто выступает как зон/i.test(r))).toBe(false);
  });
});
