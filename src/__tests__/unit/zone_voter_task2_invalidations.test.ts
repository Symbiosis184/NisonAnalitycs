// ЗАДАЧА 2: инвалидация по закрытию + полярность для книжных зон.
// Книга: ЗГ гл. 2: «Если нижняя граница зоны поддержки (т.е. минимум высокой
// белой свечи) затем будет пробита ценой закрытия, то длинную позицию следует
// закрыть. Прорывы этих зон поддержки могут происходить неоднократно в течение
// сессии, но я считаю, что пока цены закрытия держатся выше поддержки, она
// остается в силе». Полярность: ЯС гл. 11 — прежняя поддержка становится
// сопротивлением и наоборот.
import { describe, it, expect, beforeEach } from 'vitest';
import { Candle } from '../../utils/candle';
import { ZoneVoter } from '../../utils/zone_voter';

const mk = (time: number, open: number, high: number, low: number, close: number, volume = 100) =>
  new Candle({ time, open, high, low, close, volume });

// Белая свеча 40 баров назад: body=3 >= 3*prevBody(0.1) — книжная long-body зона
// [99.5 … 101.5] (low=99.5, mid=101.5).
// Закрытие ниже её low 20 баров назад (bar 46): close=98 < 99.5 → подтверждённый пробой.
describe('Задача 2: книжная полоса после пробоя по закрытию не остаётся поддержкой', () => {
  beforeEach(() => ZoneVoter.clearCache());

  const brokenSupportHistory = [
    ...Array.from({ length: 25 }, (_, i) => mk(i + 1, 99.95, 100.3, 99.7, 100.05)),
    mk(26, 100, 103.4, 99.5, 103),                       // длинная белая: зона [99.5…101.5]
    mk(27, 103, 103.2, 102.5, 102.8),                    // цена выше зоны
    mk(28, 102.8, 103.0, 102.2, 102.5),                  // цена выше зоны
    mk(29, 102.5, 102.8, 102.0, 102.2),                  // цена выше зоны
    mk(30, 102.2, 102.5, 101.8, 102.0),                  // цена выше зоны
    mk(31, 102.0, 102.3, 101.5, 101.8),                  // цена выше зоны
    mk(32, 101.8, 102.0, 101.2, 101.5),                  // цена выше зоны
    mk(33, 101.5, 101.8, 101.0, 101.2),                  // цена выше зоны
    mk(34, 101.2, 101.5, 100.8, 101.0),                  // цена выше зоны
    mk(35, 101.0, 101.2, 100.5, 100.8),                  // цена выше зоны
    mk(36, 100.8, 101.0, 100.2, 100.5),                  // цена выше зоны
    mk(37, 100.5, 100.8, 100.0, 100.2),                  // цена выше зоны
    mk(38, 100.2, 100.5, 99.8, 100.0),                   // цена выше зоны
    mk(39, 100.0, 100.2, 99.5, 99.8),                    // цена выше зоны
    mk(40, 99.8, 100.0, 99.2, 99.5),                     // цена выше зоны
    mk(41, 99.5, 99.8, 99.0, 99.2),                      // цена выше зоны
    mk(42, 99.2, 99.5, 98.8, 99.0),                      // цена выше зоны
    mk(43, 99.0, 99.2, 98.5, 98.8),                      // цена выше зоны
    mk(44, 98.8, 99.0, 98.2, 98.5),                      // цена выше зоны
    mk(45, 98.5, 98.8, 98.0, 98.2),                      // цена выше зоны
    mk(46, 98.2, 98.5, 97.5, 98.0),                      // ПРОБОЙ: close 98.0 < 99.5
    mk(47, 98.0, 98.5, 97.8, 98.2),                      // цена ниже зоны
    mk(48, 98.2, 98.8, 98.0, 98.5),                      // цена ниже зоны
    mk(49, 98.5, 99.0, 98.2, 98.8),                      // цена ниже зоны
    mk(50, 98.8, 99.2, 98.5, 99.0),                      // цена ниже зоны
  ];

  it('после закрытия ниже дальней границы зона НЕ выдаётся как поддержка', () => {
    const lastClose = brokenSupportHistory[brokenSupportHistory.length - 1].close;
    const zones = ZoneVoter.collect(lastClose, brokenSupportHistory, 'swing');
    const lb = zones.support.filter((z) => z.sources.includes('long-body'));
    expect(lb.length).toBe(0);
  });

  it('после возврата снизу и удержания над зоной — полярность: зона становится сопротивлением', () => {
    // Добавляем возврат к зоне и удержание сверху: high касается зоны, close > 101.5
    const hist = [
      ...brokenSupportHistory.slice(0, 46), // до пробоя включительно
      mk(47, 98.0, 98.5, 97.8, 98.2),       // ниже
      mk(48, 98.2, 98.8, 98.0, 98.5),       // ниже
      mk(49, 98.5, 99.0, 98.2, 98.8),       // ниже
      mk(50, 98.8, 99.5, 98.5, 99.2),       // ниже
      mk(51, 99.2, 100.0, 99.0, 99.8),      // возврат в зону (high 100 ∈ [99.5..101.5])
      mk(52, 99.8, 102.0, 99.5, 101.8),     // УДЕРЖАНИЕ: high коснулся зоны, close > 101.5
      mk(53, 101.8, 102.2, 101.5, 102.0),   // выше зоны
      mk(54, 102.0, 102.5, 101.8, 102.2),   // выше зоны
      mk(55, 102.2, 102.8, 102.0, 102.5),   // выше зоны
    ];
    const lastClose = hist[hist.length - 1].close;
    const zones = ZoneVoter.collect(lastClose, hist, 'swing');
    const lb = zones.resistance.filter((z) => z.sources.includes('long-body'));
    expect(lb.length).toBe(1);
    expect(lb[0].reasons.some((r) => /полярность.*ЯС гл\. 11/.test(r))).toBe(true);
  });
});
