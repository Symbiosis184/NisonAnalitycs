// ЗАДАЧА 4: определение касания — глубокий прокол с восстановлением это тест.
// Книга (ЗГ гл. 2): «прорывы этих зон поддержки могут происходить неоднократно
// в течение сессии, но пока цены закрытия держатся выше поддержки, она остается
// в силе». То есть внутрисессионный прокол тени ниже зоны при удержании close
// НЕ отменяет поддержку и должен считаться касанием/тестом.
import { describe, it, expect, beforeEach } from 'vitest';
import { Candle } from '../../utils/candle';
import { ZoneVoter } from '../../utils/zone_voter';

const mk = (time: number, open: number, high: number, low: number, close: number, volume = 100) =>
  new Candle({ time, open, high, low, close, volume });

describe('Задача 4: касание поддержки — низ свечи вошёл/проколол зону, close остался выше основания', () => {
  beforeEach(() => ZoneVoter.clearCache());

  // Свинг-низ на 99.5, затем глубокий прокол тенью до 98.0 при close 100.2 (> 99.5).
  // Старая логика требовала low ВНУТРИ ±halfWidth; новый критерий: c.low <= zoneTop && c.close >= zoneBottom.
  const hammerHistory = [
    ...Array.from({ length: 20 }, (_, i) => mk(i + 1, 100, 100.3, 99.7, 100)),
    mk(21, 100, 100.5, 99.5, 100.2),                     // свинг-низ 99.5
    mk(22, 100.2, 100.4, 99.8, 100.1),                   // над зоной
    mk(23, 100.1, 100.3, 99.6, 100.0),                   // лёгкое касание сверху
    mk(24, 100.0, 100.2, 98.0, 100.2),                   // ГЛУБОКИЙ ПРОКОЛ: low 98 << 99.5, close 100.2 > 99.5
    mk(25, 100.2, 100.4, 99.8, 100.3),                   // восстановление
    mk(26, 100.3, 100.5, 99.9, 100.4),                   // над зоной
    mk(27, 100.4, 100.6, 100.0, 100.5),                  // над зоной
    mk(28, 100.5, 100.7, 100.1, 100.6),                  // над зоной
    mk(29, 100.6, 100.8, 100.2, 100.7),                  // над зоной
    mk(30, 100.7, 100.9, 100.3, 100.8),                  // над зоной
    mk(31, 100.8, 101.0, 100.4, 100.9),                  // над зоной
    mk(32, 100.9, 101.1, 100.5, 101.0),                  // над зоной
    mk(33, 101.0, 101.2, 100.6, 101.1),                  // над зоной
    mk(34, 101.1, 101.3, 100.7, 101.2),                  // над зоной
    mk(35, 101.2, 101.4, 100.8, 101.3),                  // над зоной
    mk(36, 101.3, 101.5, 100.9, 101.4),                  // над зоной
    mk(37, 101.4, 101.6, 101.0, 101.5),                  // над зоной
    mk(38, 101.5, 101.7, 101.1, 101.6),                  // над зоной
    mk(39, 101.6, 101.8, 101.2, 101.7),                  // над зоной
    mk(40, 101.7, 101.9, 101.3, 101.8),                  // над зоной
  ];

  it('глубокий прокол тенью при удержании close — зона остаётся поддержкой и получает touch', () => {
    const lastClose = hammerHistory[hammerHistory.length - 1].close;
    const zones = ZoneVoter.collect(lastClose, hammerHistory, 'swing');
    // Ищем свинг-зону около 99.5 (или её кластер).
    const swingSup = zones.support.find((z) => Math.abs(z.level - 99.5) < 1.5);
    expect(swingSup).toBeDefined();
    // Зона должна иметь хотя бы одно касание (deep-pierce test).
    expect(swingSup!.touches).toBeGreaterThanOrEqual(1);
  });
});
